// ============================================================================
// v8.3.14: Derived citation unification
// ============================================================================
//
// Inline `page:N` references in CLASS_FEATURES and SYNERGIES_DB are the
// authoring source-of-truth (right next to the data they cite, easy to edit).
// At module load we walk those structures and populate two new CITATIONS
// sub-sections so all citations are queryable through a single API:
//
//   CITATIONS.classFeatures['ClassName::FeatureName']  → {book, page}
//   CITATIONS.synergies['Source→Target']               → {book, page}
//
// This is a DERIVED VIEW — modifying CITATIONS.classFeatures directly has no
// effect on the underlying CLASS_FEATURES data. To change a citation, edit
// the inline `page:N` in the source structure.
//
// All entries get `book:'HH'` since both CLASS_FEATURES and SYNERGIES_DB
// inline-citations exclusively reference the Hero's Handbook. If future
// entries need to cite GG or FF, the entry can include `book:'GG'` alongside
// `page:N` (or we'll add an explicit override mechanism).
(function unifyCitations() {
  CITATIONS.classFeatures = CITATIONS.classFeatures || {};
  CITATIONS.synergies     = CITATIONS.synergies     || {};

  // Walk CLASS_FEATURES
  for (const className in CLASS_FEATURES) {
    const features = CLASS_FEATURES[className];
    if (!Array.isArray(features)) continue;
    for (const f of features) {
      if (!f || typeof f.page !== 'number') continue;
      const key = className + '::' + f.name;
      CITATIONS.classFeatures[key] = {
        book: f.book || 'HH',
        page: f.page,
        // v8.6.1: approx entries (feature located only to its class section
        // during the line-ref→page repair) keep the ~ prefix downstream.
        ...(f.approx ? { approx: true } : {}),
      };
    }
  }

  // Walk SYNERGIES_DB
  for (const e of SYNERGIES_DB) {
    if (!e || typeof e.page !== 'number') continue;
    const key = e.source + '\u2192' + e.target;  // Unicode RIGHTWARDS ARROW
    CITATIONS.synergies[key] = {
      book: e.book || 'HH',
      page: e.page,
    };
  }
})();
